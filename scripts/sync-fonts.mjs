/**
 * M0-T02 — font foundation generator.
 *
 * Copies the pinned self-hosted woff2 files into public/fonts and regenerates
 * src/styles/fonts.css from them.
 *
 * Why a generator: the Design SOT pins an exact set of families and weights
 * (docs/design/00_DESIGN_PIXEL_SOT_FINAL_v1.0.md section 2.3). Hand-maintained
 * @font-face blocks drift from that list silently. Running this script is the
 * only sanctioned way to change the font layer, and `fonts.test.ts` fails if
 * the committed CSS no longer matches what the script would emit.
 *
 * Fonts are copied at build time from the @fontsource packages and served from
 * our own origin. Nothing is fetched from a CDN at runtime.
 *
 * Usage: pnpm fonts:sync
 */
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const FONT_DIR = join(ROOT, 'public', 'fonts')
const OUT_CSS = join(ROOT, 'src', 'styles', 'fonts.css')

/**
 * Exactly the families and weights frozen by Design SOT section 2.3.
 * Adding a weight here without a corresponding SOT change is a contract breach.
 */
export const PINNED_FONTS = [
  { family: 'Be Vietnam Pro', pkg: 'be-vietnam-pro', weights: [400, 500, 600] },
  { family: 'Archivo', pkg: 'archivo', weights: [700] },
  { family: 'IBM Plex Mono', pkg: 'ibm-plex-mono', weights: [500] },
  // DEC-HD-12: Corrected Design Revision screens only, never the legacy product UI.
  { family: 'Space Grotesk', pkg: 'space-grotesk', weights: [400, 500, 600, 700] },
]

/** Vietnamese is required: the product locale is vi-VN. Cyrillic is not shipped. */
export const SUBSETS = ['latin', 'latin-ext', 'vietnamese']

/**
 * Fontsource puts unicode-range only in the combined per-weight stylesheet
 * (e.g. 400.css); the per-subset files omit it. So parse the combined file and
 * pick the @font-face block whose src names the subset file we ship.
 */
function unicodeRangeFor(pkg, subset, weight) {
  const css = readFileSync(join(ROOT, 'node_modules', '@fontsource', pkg, `${weight}.css`), 'utf8')
  const target = `${pkg}-${subset}-${weight}-normal.woff2`
  const block = css
    .split('@font-face')
    .find((chunk) => chunk.includes(target) && chunk.includes('unicode-range'))
  const match = block?.match(/unicode-range:\s*([^;]+);/)
  if (!match?.[1]) throw new Error(`no unicode-range for ${target} in ${pkg}/${weight}.css`)
  return match[1].trim()
}

export function buildFontCss() {
  const blocks = []
  for (const { family, pkg, weights } of PINNED_FONTS) {
    for (const weight of weights) {
      for (const subset of SUBSETS) {
        const file = `${pkg}-${subset}-${weight}-normal.woff2`
        blocks.push(
          [
            '@font-face {',
            `  font-family: '${family}';`,
            '  font-style: normal;',
            `  font-weight: ${weight};`,
            // `block` keeps text invisible until the real face is ready instead of
            // painting a fallback and reflowing. Pixel QA captures after
            // document.fonts.ready, so there is no visible block period there, and
            // product users never see a fallback-to-real shift.
            '  font-display: block;',
            `  src: url('/fonts/${file}') format('woff2');`,
            `  unicode-range: ${unicodeRangeFor(pkg, subset, weight)};`,
            '}',
          ].join('\n'),
        )
      }
    }
  }
  return [
    '/*',
    ' * GENERATED by scripts/sync-fonts.mjs — do not edit by hand.',
    ' * Run `pnpm fonts:sync` to regenerate.',
    ' *',
    ' * Families and weights are frozen by Design SOT section 2.3:',
    ' *   Be Vietnam Pro 400 / 500 / 600   default product UI',
    ' *   Archivo 700                       approved display usage only',
    ' *   IBM Plex Mono 500                 approved technical/meta usage only',
    ' *   Space Grotesk 400 / 500 / 600 / 700   Corrected Design Revision screens only (DEC-HD-12)',
    ' *',
    ' * Files are self-hosted under /fonts. No runtime CDN request is made.',
    ' */',
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n')
}

export function expectedFontFiles() {
  return PINNED_FONTS.flatMap(({ pkg, weights }) =>
    weights.flatMap((weight) => SUBSETS.map((subset) => `${pkg}-${subset}-${weight}-normal.woff2`)),
  )
}

function main() {
  mkdirSync(FONT_DIR, { recursive: true })
  const wanted = new Set(expectedFontFiles())

  for (const stale of readdirSync(FONT_DIR)) {
    if (!wanted.has(stale)) unlinkSync(join(FONT_DIR, stale))
  }

  for (const { pkg, weights } of PINNED_FONTS) {
    for (const weight of weights) {
      for (const subset of SUBSETS) {
        const file = `${pkg}-${subset}-${weight}-normal.woff2`
        copyFileSync(
          join(ROOT, 'node_modules', '@fontsource', pkg, 'files', file),
          join(FONT_DIR, file),
        )
      }
    }
  }

  mkdirSync(dirname(OUT_CSS), { recursive: true })
  writeFileSync(OUT_CSS, buildFontCss())
  console.log(`synced ${wanted.size} font files and regenerated ${OUT_CSS}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
